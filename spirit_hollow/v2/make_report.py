def calibration():
    c = json.load(open(os.path.join(HERE, "output", "calibration.json")))
    rows = ["| World | Fairway | First cut | Penalty (water, OB, lost) | Trouble (penalty, trees, long grass) | "
            "Sand | > 40 yds offline |", "|---|---|---|---|---|---|---|"]
    for k, v in c.items():
        m = v["mean"]
        rows.append(f"| {k} | {m['fairway']:.0%} | {m['first_cut']:.0%} | {m['penalty']:.1%} | {m['trouble']:.0%} | "
                    f"{m['sand']:.1%} | {m['beyond40']:.1%} |")
    rows.append("| Published 0-5 hcp (research.md) | ~49% (Shot Scope, driver) | — | 1-3% (Shot Scope) | "
                "~12% (Arccos scratch-4.9) | — | ~7% (Stagner) |")
    return "\n".join(rows)


def main():
    buf = io.StringIO()
