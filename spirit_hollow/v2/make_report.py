def calibration():
    c = json.load(open(os.path.join(HERE, "output", "calibration.json")))
    rows = ["| World | Fairway | First cut | Penalty (water, OB, lost) | Trouble (penalty, trees, long grass) | "
            "Sand | > 40 yds offline |", "|---|---|---|---|---|---|---|"]
    for k, v in c.items():
        m = v["mean"]
        rows.append(f"| {k} | {m['fairway']:.0%} | {m['first_cut']:.0%} | {m['penalty']:.1%} | {m['trouble']:.0%} | "
                    f"{m['sand']:.1%} | {m['beyond40']:.1%} |")
    rows.append("| Published 0-5 hcp (research.md) | ~49% (Shot Scope, driver) | — | 1-3% (Shot Scope) | "
                "~12% (Arccos scratch-4.9) | — | ~7% (Stagner) |")
    return "\n".join(rows)


def main():
    buf = io.StringIO()
    with redirect_stdout(buf):
        tables.main()
    rr = json.load(open(os.path.join(HERE, "output", "reverse_regret.json")))
    md = [HEAD, VERDICT, "\n## Calibration (Driver at its best aim, mean of the 16 tee holes)\n", calibration(),
          "\nThe golfer-stated 70-yd pattern makes the model straighter than published 0-5 handicap data "
          "(beyond-40 rate 2.5% vs ~7%); at an 82-yd pattern the tails match (picks at 82 are in the sensitivity "
          "table). With full roll v2's fairway share (48%) matches the published 49%. Its penalty rate (7.7%) is above "
          "the published 1-3%: Spirit Hollow has more water, OB and long grass in play than an average course, and the "
          "lost-ball share in the long grass is an unpublished assumption (sensitivity: 'lost ball rare'). "
          "Calibration cannot settle the remaining differences; the golfer's own fairway and miss data would.\n",
          f"\n## Reverse check\n\nIf v1's world (its central settings) were the truth, v2's plays would cost "
          f"**{rr['black_round_total']:.2f} strokes** per Black-tee round versus v1's own best plays. Per hole: "
          + ", ".join(f"{k} {v:+.3f}" for k, v in rr.items() if k != "black_round_total") + ".\n",
          "\n![EV vs aim](output/ev_curves.png)\n", buf.getvalue()]
    open(os.path.join(HERE, "REPORT.md"), "w").write("\n".join(md))
    print("wrote REPORT.md")


